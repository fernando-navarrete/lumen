import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import '../../tool/prune_cargo_lock.dart';

const _header = '''# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4
''';

String _block(String name, String version, {String extra = ''}) =>
    '''
[[package]]
name = "$name"
version = "$version"
source = "registry+https://github.com/rust-lang/crates.io-index"
$extra''';

String _lock(List<String> blocks) => '$_header\n${blocks.join('\n')}';

void main() {
  group('parseCargoTree', () {
    test('reads registry, git and path crates and strips the suffixes', () {
      const tree = '''
gogdl_flutter v1.4.3 (/work/rust)
reqwest v0.13.5
gogdl-lib v1.3.2 (https://github.com/x/gogdl-lib.git?tag=v1.3.2#8df36d0b)
serde_derive v1.0.228 (proc-macro)
tokio v1.53.1 (*)
''';
      expect(parseCargoTree(tree), {
        'gogdl_flutter 1.4.3',
        'reqwest 0.13.5',
        'gogdl-lib 1.3.2',
        'serde_derive 1.0.228',
        'tokio 1.53.1',
      });
    });

    test('keeps two versions of one crate apart', () {
      expect(parseCargoTree('base64 v0.22.1\nbase64 v0.23.1 (*)\n'), {
        'base64 0.22.1',
        'base64 0.23.1',
      });
    });

    test('ignores blank lines, warnings and headings', () {
      const tree = '''

warning: nothing to print
[dev-dependencies]
serde v1.0.228
''';
      expect(parseCargoTree(tree), {'serde 1.0.228'});
    });
  });

  group('pruneCargoLock', () {
    final lock = _lock([
      _block('a', '1.0.0', extra: 'dependencies = [\n "quinn",\n]\n'),
      _block('quinn-proto', '0.11.17'),
      _block('base64', '0.22.1'),
      _block('base64', '0.23.1'),
    ]);

    test('keeps the header and listed blocks, drops the rest', () {
      final r = pruneCargoLock(lock, {'a 1.0.0', 'base64 0.23.1'});

      expect(r.dropped, ['quinn-proto 0.11.17', 'base64 0.22.1']);
      expect(r.missing, isEmpty);
      expect(
        r.lock,
        _lock([
          _block('a', '1.0.0', extra: 'dependencies = [\n "quinn",\n]\n'),
          _block('base64', '0.23.1'),
        ]),
      );
    });

    test('a crate at another version than the tree lists is dropped', () {
      final r = pruneCargoLock(lock, {'a 1.0.0', 'base64 0.22.1'});

      expect(r.dropped, contains('base64 0.23.1'));
      expect(r.lock, contains('version = "0.22.1"'));
      expect(r.lock, isNot(contains('0.23.1')));
    });

    test('reports a tree crate the lock does not list', () {
      final r = pruneCargoLock(lock, {'a 1.0.0', 'ghost 9.9.9'});

      expect(r.missing, ['ghost 9.9.9']);
    });
  });

  group('runPrune', () {
    late Directory dir;
    setUp(() => dir = Directory.systemTemp.createTempSync('prune_lock_'));
    tearDown(() => dir.deleteSync(recursive: true));

    String path(String name) => '${dir.path}/$name';

    int run(String lock, String tree) {
      File(path('in.lock')).writeAsStringSync(lock);
      File(path('tree.txt')).writeAsStringSync(tree);
      return runPrune([path('in.lock'), path('tree.txt'), path('out.lock')]);
    }

    test('writes the pruned lock and exits 0', () {
      final code = run(
        _lock([_block('a', '1.0.0'), _block('quinn-proto', '0.11.17')]),
        'a v1.0.0\n',
      );

      expect(code, 0);
      expect(
        File(path('out.lock')).readAsStringSync(),
        _lock([_block('a', '1.0.0')]),
      );
    });

    test('exits 2 on an empty tree and writes nothing', () {
      expect(run(_lock([_block('a', '1.0.0')]), '\n'), 2);
      expect(File(path('out.lock')).existsSync(), isFalse);
    });

    test('exits 2 when the tree has a crate the lock lacks', () {
      expect(run(_lock([_block('a', '1.0.0')]), 'a v1.0.0\nghost v1.0.0\n'), 2);
      expect(File(path('out.lock')).existsSync(), isFalse);
    });

    test('exits 2 on a missing input or wrong arguments', () {
      expect(
        runPrune([path('nope.lock'), path('nope.txt'), path('out.lock')]),
        2,
      );
      expect(runPrune(['one']), 2);
    });
  });
}
