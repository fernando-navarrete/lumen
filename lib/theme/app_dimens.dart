/// Corner radii shared across the app.
class AppRadii {
  /// Mini chips: filter chips, small badges.
  static const double chipSmall = 8.0;

  /// Chips and small buttons: nav pills, back pill, refresh chip.
  static const double chip = 9.0;

  /// Small controls: inputs, selects, code blocks.
  static const double control = 10.0;

  /// Large call-to-action buttons (hero Play / Configure).
  static const double buttonLarge = 11.0;

  /// Cards, panels, cover images.
  static const double card = 13.0;

  /// Wide list rows (downloads cards).
  static const double cardLarge = 14.0;

  /// Glass section cards (settings, facts panel).
  static const double section = 16.0;

  /// Hero banners.
  static const double hero = 18.0;

  /// The large login split panel.
  static const double panel = 22.0;
}

/// Vertical/horizontal gaps between elements.
class AppSpacing {
  static const double xs = 8.0;
  static const double sm = 12.0;
  static const double md = 16.0;
  static const double lg = 24.0;
  static const double xl = 32.0;
}
